// Command asmgen writes the layago GEMM microkernels, gemm_arm64.s and
// gemm_amd64.s, into the tensor package:
//
//	go generate ./tensor
//
// It is plain Go that prints Go assembly, so it needs no third-party
// generator, and TestGeneratedAssemblyIsCurrent fails when a committed file
// drifts from this program's output.
//
// Both kernels keep the portable kernel's arithmetic: the weights are packed
// K-major in panels of nr output columns, and each accumulator lane is one
// output element updated by one fused multiply-add per K step, in order. A
// row value of x is broadcast (AVX2) or taken by lane (NEON) and multiplied
// into nr consecutive columns, so no reduction across lanes ever reorders a
// sum. Each call covers one tile and the K steps it is given, and the Go
// loops around it bound that to kChunk steps.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
)

func main() {
	dir := flag.String("dir", ".", "directory of the tensor package")
	flag.Parse()
	files := Files()
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := os.WriteFile(filepath.Join(*dir, name), files[name], 0o644); err != nil { //nolint:gosec // G306: generated source files are world-readable like every other source file
			log.Fatal(err)
		}
	}
}

// Files returns every generated file keyed by its name in the tensor package.
func Files() map[string][]byte {
	return map[string][]byte{
		"gemm_arm64.s": arm64File(),
		"gemm_amd64.s": amd64File(),
	}
}

type writer struct{ bytes.Buffer }

func (w *writer) p(format string, args ...any) {
	fmt.Fprintf(&w.Buffer, format, args...)
	w.WriteByte('\n')
}

func header(w *writer) {
	w.p("// Code generated by tensor/asmgen; DO NOT EDIT.")
	w.p("")
	w.p("//go:build !purego")
	w.p("")
	w.p("#include \"textflag.h\"")
}

// ---------------------------------------------------------------------------
// arm64 NEON: 8x8 tiles.
//
// V0-V15 accumulate the tile (row r in V2r for columns 0-3 and V2r+1 for
// columns 4-7), V16-V23 hold four consecutive K values of each of the eight
// rows of x, V24-V31 hold packed weights. The main loop consumes four K steps
// per iteration with FMLA by element (lane j of a row register is x[r][k+j]),
// the tail one step at a time with a replicated load and a vector FMLA. R6-R13
// point at the eight rows.
// ---------------------------------------------------------------------------

const (
	neonMR = 8
	neonNR = 8
)

// fmlaElem encodes FMLA Vd.4S, Vn.4S, Vm.S[lane], which no Go assembler
// accepts. Encoding: 0 Q=1 0 01111 1 sz=0 L M Rm 0001 H 0 Rn Rd, with the
// lane in H:L and the element register in M:Rm.
func fmlaElem(d, n, m, lane int) uint32 {
	checkVectorRegs(d, n, m)
	if lane < 0 || lane > 3 {
		panic(fmt.Sprintf("asmgen: lane %d of a 4S register", lane))
	}
	word := 0x4F801000 | (lane&1)<<21 | (m>>4)<<20 | (m&15)<<16 | (lane>>1)<<11 | n<<5 | d
	return uint32(word) //nolint:gosec // G115: every field is range-checked above, so word < 2^32
}

// The int8 path's widening and conversion are WORD encodings too. Go 1.27's
// assembler knows VSXTL, VSXTL2 and VSCVTF, but Go 1.26 (the go.mod minimum,
// and the toolchain CI, release.yml and the Dockerfile pin) rejects them, so
// spelling them as mnemonics broke every arm64 build on the pinned
// toolchain. A WORD assembles on every Go version.

// sxtl encodes SXTL Vd.<2w>, Vn.<w> (upper false) or SXTL2 (upper true), the
// alias of SSHLL/SSHLL2 with shift 0 that sign-extends each srcBits-wide
// lane of the lower (SXTL) or upper (SXTL2) half of Vn to twice its width.
// Encoding: 0 Q 0 011110 immh immb=000 101001 Rn Rd, immh = 0001 for bytes
// and 0010 for halfwords.
func sxtl(d, n, srcBits int, upper bool) uint32 {
	checkVectorRegs(d, n)
	var immh int
	switch srcBits {
	case 8:
		immh = 1
	case 16:
		immh = 2
	default:
		panic(fmt.Sprintf("asmgen: SXTL from %d-bit lanes", srcBits))
	}
	q := 0
	if upper {
		q = 1
	}
	word := 0x0F00A400 | q<<30 | immh<<19 | n<<5 | d
	return uint32(word) //nolint:gosec // G115: every field is range-checked above, so word < 2^32
}

// scvtf4s encodes SCVTF Vd.4S, Vn.4S (signed int32 to float32 per lane,
// exact for |x| < 2^24). Encoding: 0 Q=1 0 01110 0 sz=0 10000 11101 10 Rn Rd.
func scvtf4s(d, n int) uint32 {
	checkVectorRegs(d, n)
	return uint32(0x4E21D800 | n<<5 | d) //nolint:gosec // G115: d and n are range-checked above
}

func checkVectorRegs(regs ...int) {
	for _, r := range regs {
		if r < 0 || r > 31 {
			panic(fmt.Sprintf("asmgen: vector register V%d does not exist", r))
		}
	}
}

// widenInt8 emits SXTL (upper false) or SXTL2 of V<n> into V<d>; srcBits
// is 8 (B8/B16 to H8) or 16 (H4/H8 to S4). The comment spells the
// instruction in Go 1.27's syntax, which the words were checked against.
func widenInt8(w *writer, d, n, srcBits int, upper bool) {
	op, src, dst := "VSXTL", "B8", "H8"
	if srcBits == 16 {
		src, dst = "H4", "S4"
	}
	if upper {
		op = "VSXTL2"
		if srcBits == 8 {
			src = "B16"
		} else {
			src = "H8"
		}
	}
	w.p("\tWORD\t$0x%08x // %s V%d.%s, V%d.%s", sxtl(d, n, srcBits, upper), op, n, src, d, dst)
}

// convertInt32 emits SCVTF V<n>.4S into V<d>.4S.
func convertInt32(w *writer, d, n int) {
	w.p("\tWORD\t$0x%08x // VSCVTF V%d.S4, V%d.S4", scvtf4s(d, n), n, d)
}

func arm64File() []byte {
	w := &writer{}
	header(w)
	neonKernel(w, "neonF32", false)
	neonKernel(w, "neonQ8", true)
	return w.Bytes()
}

func neonKernel(w *writer, name string, q8 bool) {
	bType := "*float32"
	if q8 {
		bType = "*int8"
	}
	w.p("")
	w.p("// func %s(kc int, a *float32, lda int, b %s, c *float32, acc int)", name, bType)
	w.p("TEXT ·%s(SB), NOSPLIT, $0-48", name)
	w.p("\tMOVD\tkc+0(FP), R0")
	w.p("\tMOVD\ta+8(FP), R6")
	w.p("\tMOVD\tlda+16(FP), R2")
	w.p("\tMOVD\tb+24(FP), R3")
	w.p("\tMOVD\tc+32(FP), R4")
	w.p("\tMOVD\tacc+40(FP), R5")
	for r := 1; r < neonMR; r++ {
		w.p("\tADD\tR2, R%d, R%d", 5+r, 6+r)
	}
	w.p("\tCBZ\tR5, %s_zero", name)
	w.p("\tMOVD\tR4, R16")
	for r := 0; r < 16; r += 4 {
		op, addr := "VLD1.P", "64(R16)"
		if r == 12 {
			op, addr = "VLD1", "(R16)"
		}
		w.p("\t%s\t%s, [V%d.S4, V%d.S4, V%d.S4, V%d.S4]", op, addr, r, r+1, r+2, r+3)
	}
	w.p("\tB\t%s_ready", name)
	w.p("%s_zero:", name)
	for v := 0; v < 16; v++ {
		w.p("\tVEOR\tV%d.B16, V%d.B16, V%d.B16", v, v, v)
	}
	w.p("%s_ready:", name)
	w.p("\tLSR\t$2, R0, R14")
	w.p("\tAND\t$3, R0, R15")
	w.p("\tCBZ\tR14, %s_tail", name)
	w.p("%s_loop4:", name)
	for r := 0; r < neonMR; r++ {
		w.p("\tVLD1.P\t16(R%d), [V%d.S4]", 6+r, 16+r)
	}
	// fmlas emits the 16 multiply-adds of K step k+lane, taking the packed
	// weights for columns 0-3 from register lo and 4-7 from hi.
	fmlas := func(lane, lo, hi int) {
		for r := 0; r < neonMR; r++ {
			w.p("\tWORD\t$0x%08x // FMLA V%d.S4, V%d.S4, V%d.S[%d]", fmlaElem(2*r, lo, 16+r, lane), 2*r, lo, 16+r, lane)
			w.p("\tWORD\t$0x%08x // FMLA V%d.S4, V%d.S4, V%d.S[%d]", fmlaElem(2*r+1, hi, 16+r, lane), 2*r+1, hi, 16+r, lane)
		}
	}
	if q8 {
		// Two K steps per 16-byte load: sign-extend int8 -> int16 -> int32,
		// convert to float32 (exact for |q| <= 127), then multiply-add.
		for half := 0; half < 2; half++ {
			w.p("\tVLD1.P\t16(R3), [V24.B16]")
			widenInt8(w, 25, 24, 8, false)
			widenInt8(w, 26, 24, 8, true)
			widenInt8(w, 27, 25, 16, false)
			widenInt8(w, 28, 25, 16, true)
			widenInt8(w, 29, 26, 16, false)
			widenInt8(w, 30, 26, 16, true)
			for v := 27; v <= 30; v++ {
				convertInt32(w, v, v)
			}
			fmlas(2*half, 27, 28)
			fmlas(2*half+1, 29, 30)
		}
	} else {
		w.p("\tVLD1.P\t64(R3), [V24.S4, V25.S4, V26.S4, V27.S4]")
		w.p("\tVLD1.P\t64(R3), [V28.S4, V29.S4, V30.S4, V31.S4]")
		for lane := 0; lane < 4; lane++ {
			fmlas(lane, 24+2*lane, 25+2*lane)
		}
	}
	w.p("\tSUB\t$1, R14, R14")
	w.p("\tCBNZ\tR14, %s_loop4", name)
	w.p("%s_tail:", name)
	w.p("\tCBZ\tR15, %s_store", name)
	w.p("%s_tail1:", name)
	for r := 0; r < neonMR; r++ {
		w.p("\tVLD1R.P\t4(R%d), [V%d.S4]", 6+r, 16+r)
	}
	lo, hi := 24, 25
	if q8 {
		w.p("\tVLD1.P\t8(R3), [V24.B8]")
		widenInt8(w, 25, 24, 8, false)
		widenInt8(w, 27, 25, 16, false)
		widenInt8(w, 28, 25, 16, true)
		convertInt32(w, 27, 27)
		convertInt32(w, 28, 28)
		lo, hi = 27, 28
	} else {
		w.p("\tVLD1.P\t32(R3), [V24.S4, V25.S4]")
	}
	for r := 0; r < neonMR; r++ {
		w.p("\tVFMLA\tV%d.S4, V%d.S4, V%d.S4", lo, 16+r, 2*r)
		w.p("\tVFMLA\tV%d.S4, V%d.S4, V%d.S4", hi, 16+r, 2*r+1)
	}
	w.p("\tSUB\t$1, R15, R15")
	w.p("\tCBNZ\tR15, %s_tail1", name)
	w.p("%s_store:", name)
	for r := 0; r < 16; r += 4 {
		op, addr := "VST1.P", "64(R4)"
		if r == 12 {
			op, addr = "VST1", "(R4)"
		}
		w.p("\t%s\t[V%d.S4, V%d.S4, V%d.S4, V%d.S4], %s", op, r, r+1, r+2, r+3, addr)
	}
	w.p("\tRET")
}

// ---------------------------------------------------------------------------
// amd64 AVX2+FMA: 6x16 tiles.
//
// Y0-Y11 accumulate the tile (row r in Y2r for columns 0-7 and Y2r+1 for
// columns 8-15), Y12-Y13 hold the packed weights of one K step, Y14-Y15
// alternate as the broadcast x[r][k]. Rows 0-2 are addressed from SI and rows
// 3-5 from R9 = SI + 3*lda, with R8 = lda. The main loop is unrolled over four
// K steps.
// ---------------------------------------------------------------------------

const (
	avxMR = 6
	avxNR = 16
)

func amd64File() []byte {
	w := &writer{}
	header(w)
	avxKernel(w, "avx2F32", false)
	avxKernel(w, "avx2Q8", true)
	w.p("")
	w.p("// func cpuid(eaxArg, ecxArg uint32) (eax, ebx, ecx, edx uint32)")
	w.p("TEXT ·cpuid(SB), NOSPLIT, $0-24")
	w.p("\tMOVL\teaxArg+0(FP), AX")
	w.p("\tMOVL\tecxArg+4(FP), CX")
	w.p("\tCPUID")
	w.p("\tMOVL\tAX, eax+8(FP)")
	w.p("\tMOVL\tBX, ebx+12(FP)")
	w.p("\tMOVL\tCX, ecx+16(FP)")
	w.p("\tMOVL\tDX, edx+20(FP)")
	w.p("\tRET")
	w.p("")
	w.p("// func xgetbv() (eax, edx uint32)")
	w.p("TEXT ·xgetbv(SB), NOSPLIT, $0-8")
	w.p("\tMOVL\t$0, CX")
	w.p("\tXGETBV")
	w.p("\tMOVL\tAX, eax+0(FP)")
	w.p("\tMOVL\tDX, edx+4(FP)")
	w.p("\tRET")
	return w.Bytes()
}

// avxRow returns the address of x[r][k+step] for the unrolled step.
func avxRow(r, step int) string {
	disp := ""
	if step > 0 {
		disp = fmt.Sprint(4 * step)
	}
	switch r {
	case 0:
		return disp + "(SI)"
	case 1:
		return disp + "(SI)(R8*1)"
	case 2:
		return disp + "(SI)(R8*2)"
	case 3:
		return disp + "(R9)"
	case 4:
		return disp + "(R9)(R8*1)"
	default:
		return disp + "(R9)(R8*2)"
	}
}

func avxKernel(w *writer, name string, q8 bool) {
	bType, bStep := "*float32", 64
	if q8 {
		bType, bStep = "*int8", 16
	}
	w.p("")
	w.p("// func %s(kc int, a *float32, lda int, b %s, c *float32, acc int)", name, bType)
	w.p("TEXT ·%s(SB), NOSPLIT, $0-48", name)
	w.p("\tMOVQ\tkc+0(FP), DI")
	w.p("\tMOVQ\ta+8(FP), SI")
	w.p("\tMOVQ\tlda+16(FP), R8")
	w.p("\tMOVQ\tb+24(FP), DX")
	w.p("\tMOVQ\tc+32(FP), CX")
	w.p("\tMOVQ\tacc+40(FP), AX")
	w.p("\tLEAQ\t(SI)(R8*2), R9")
	w.p("\tADDQ\tR8, R9")
	w.p("\tTESTQ\tAX, AX")
	w.p("\tJZ\t%s_zero", name)
	for v := 0; v < 2*avxMR; v++ {
		w.p("\tVMOVUPS\t%d(CX), Y%d", 32*v, v)
	}
	w.p("\tJMP\t%s_ready", name)
	w.p("%s_zero:", name)
	for v := 0; v < 2*avxMR; v++ {
		w.p("\tVXORPS\tY%d, Y%d, Y%d", v, v, v)
	}
	w.p("%s_ready:", name)
	w.p("\tMOVQ\tDI, R10")
	w.p("\tSHRQ\t$2, R10")
	w.p("\tANDQ\t$3, DI")
	w.p("\tTESTQ\tR10, R10")
	w.p("\tJZ\t%s_tail", name)
	step := func(s int) {
		if q8 {
			w.p("\tVPMOVSXBD\t%d(DX), Y12", 16*s)
			w.p("\tVPMOVSXBD\t%d(DX), Y13", 16*s+8)
			w.p("\tVCVTDQ2PS\tY12, Y12")
			w.p("\tVCVTDQ2PS\tY13, Y13")
		} else {
			w.p("\tVMOVUPS\t%d(DX), Y12", 64*s)
			w.p("\tVMOVUPS\t%d(DX), Y13", 64*s+32)
		}
		for r := 0; r < avxMR; r++ {
			bc := 14 + r%2
			w.p("\tVBROADCASTSS\t%s, Y%d", avxRow(r, s), bc)
			w.p("\tVFMADD231PS\tY12, Y%d, Y%d", bc, 2*r)
			w.p("\tVFMADD231PS\tY13, Y%d, Y%d", bc, 2*r+1)
		}
	}
	w.p("%s_loop4:", name)
	for s := 0; s < 4; s++ {
		step(s)
	}
	w.p("\tADDQ\t$16, SI")
	w.p("\tADDQ\t$16, R9")
	w.p("\tADDQ\t$%d, DX", 4*bStep)
	w.p("\tDECQ\tR10")
	w.p("\tJNZ\t%s_loop4", name)
	w.p("%s_tail:", name)
	w.p("\tTESTQ\tDI, DI")
	w.p("\tJZ\t%s_store", name)
	w.p("%s_tail1:", name)
	step(0)
	w.p("\tADDQ\t$4, SI")
	w.p("\tADDQ\t$4, R9")
	w.p("\tADDQ\t$%d, DX", bStep)
	w.p("\tDECQ\tDI")
	w.p("\tJNZ\t%s_tail1", name)
	w.p("%s_store:", name)
	for v := 0; v < 2*avxMR; v++ {
		w.p("\tVMOVUPS\tY%d, %d(CX)", v, 32*v)
	}
	w.p("\tVZEROUPPER")
	w.p("\tRET")
}
