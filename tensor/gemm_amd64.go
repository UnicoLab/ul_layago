//go:build !purego

package tensor

var avx2Kernel = &microkernel{
	id: KernelAVX2, mr: 6, nr: 16,
	blockM: 48, blockN: 32,
	f32: avx2F32, q8: avx2Q8,
}

// hasAVX2FMA is read once: the kernel needs AVX2 and FMA, and the operating
// system must save the YMM state (OSXSAVE with XCR0 bits 1 and 2).
var hasAVX2FMA = detectAVX2FMA()

func detectAVX2FMA() bool {
	maxLeaf, _, _, _ := cpuid(0, 0)
	if maxLeaf < 7 {
		return false
	}
	_, _, ecx1, _ := cpuid(1, 0)
	const fma, osxsave, avx = 1 << 12, 1 << 27, 1 << 28
	if ecx1&fma == 0 || ecx1&osxsave == 0 || ecx1&avx == 0 {
		return false
	}
	if xcr0, _ := xgetbv(); xcr0&6 != 6 {
		return false
	}
	_, ebx7, _, _ := cpuid(7, 0)
	return ebx7&(1<<5) != 0
}

func archMicrokernel() *microkernel {
	if hasAVX2FMA {
		return avx2Kernel
	}
	return nil
}

